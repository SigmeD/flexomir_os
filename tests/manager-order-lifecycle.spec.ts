test('invalid agreed date blocks manager Send without changing the order', async ({ page }) => {
  await page.goto('/?view=manager-orders')
  await page.getByRole('button', { name: 'Открыть заказ DEMO-003' }).click()
  await chooseMore(page, 'Изменить')
  const agreed = page.getByLabel('Согласованный срок', { exact: true })
  await agreed.fill('31.11.2026')
  await agreed.press('Tab')
  await expect(agreed).toHaveAttribute('aria-invalid', 'true')
  await expect(page.getByRole('button', { name: 'Отправить заказ', exact: true })).toBeDisabled()
  await agreed.fill('26.11.2026')
  await expect(page.getByRole('button', { name: 'Отправить заказ', exact: true })).toBeEnabled()
})
