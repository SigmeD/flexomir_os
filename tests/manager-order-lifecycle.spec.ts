import { expect, test } from '@playwright/test'
import { chooseFormOption, chooseMore, commitItem, confirmClientSend, fillItem, setDemoRole } from './helpers/orders'

test('manager sends a complete order and the client sees the agreed date', async ({ page }, testInfo) => {
  await page.goto('/?view=manager-orders&demoTools=1')
  await page.getByRole('button', { name: 'Добавить заказ', exact: true }).click()
  const id = await page.getByTestId('order-composer').getAttribute('data-order-id')
  const send = page.getByRole('button', { name: 'Отправить заказ', exact: true })
  await expect(send).toBeDisabled()
  await chooseFormOption(page, 'Компания', 'Компания 01')
  await page.getByRole('button', { name: 'Добавить позицию', exact: true }).click()
  await fillItem(page)
  await commitItem(page)
  await page.getByLabel('Желаемый срок', { exact: true }).fill('16.12.2026')
  await expect(send).toBeDisabled()
  await page.getByLabel('Согласованный срок', { exact: true }).fill('20.12.2026')
  await expect(send).toBeEnabled()
  await page.evaluate(() => window.scrollTo(0, 0))
  await page.screenshot({ path: testInfo.outputPath('manager-agreed-date.png'), fullPage: true, animations: 'disabled' })
  await send.click()
  await expect(page.getByTestId('order-detail-status')).toHaveText('На рассмотрении')
  await expect(page.getByLabel('Согласованный срок', { exact: true })).toHaveValue('20.12.2026')
  await setDemoRole(page, 'client')
  await page.getByRole('button', { name: 'Открыть заказ ' + id }).click()
  await expect(page.getByLabel('Желаемый срок', { exact: true })).toHaveValue('16.12.2026')
  await expect(page.getByLabel('Согласованный срок', { exact: true })).toHaveValue('20.12.2026')
  await expect(page.getByLabel('Согласованный срок', { exact: true })).toHaveAttribute('readonly', '')
  await page.evaluate(() => window.scrollTo(0, 0))
  await page.screenshot({ path: testInfo.outputPath('client-agreed-date.png'), fullPage: true, animations: 'disabled' })
  await page.getByRole('button', { name: 'Ещё' }).click()
  await expect(page.getByRole('menuitem', { name: 'Изменить' })).toHaveCount(0)
})

test('manager sets agreed date on a client order without changing its review status', async ({ page }) => {
  await page.goto('/?view=client-orders&demoTools=1')
  await page.getByRole('button', { name: 'Добавить заказ', exact: true }).click()
  const id = await page.getByTestId('order-composer').getAttribute('data-order-id')
  await page.getByRole('button', { name: 'Добавить позицию', exact: true }).click()
  await fillItem(page)
  await commitItem(page)
  await page.getByRole('button', { name: 'Передать менеджеру (демо)' }).click()
  await confirmClientSend(page)
  await setDemoRole(page, 'manager')
  await page.getByRole('button', { name: 'Открыть заказ ' + id }).click()
  await chooseMore(page, 'Изменить')
  const agreed = page.getByLabel('Согласованный срок', { exact: true })
  await expect(agreed).toBeEditable()
  await agreed.fill('22.12.2026')
  await page.getByRole('button', { name: 'Отправить заказ', exact: true }).click()
  await expect(page.getByTestId('order-detail-status')).toHaveText('На рассмотрении')
  await setDemoRole(page, 'client')
  await page.getByRole('button', { name: 'Открыть заказ ' + id }).click()
  await expect(page.getByLabel('Согласованный срок', { exact: true })).toHaveValue('22.12.2026')
})

test('manager edits a production order and preserves Work status', async ({ page }) => {
  await page.goto('/?view=manager-orders&demoTools=1')
  await page.getByRole('button', { name: 'Открыть заказ DEMO-003' }).click()
  await chooseMore(page, 'Изменить')
  await expect(page.getByTestId('order-composer')).toBeVisible()
  await page.getByRole('button', { name: 'Изменить позицию 1' }).click()
  await page.getByLabel('Количество', { exact: true }).fill('12000')
  await commitItem(page)
  await page.getByLabel('Согласованный срок', { exact: true }).fill('25.11.2026')
  await page.getByRole('button', { name: 'Отправить заказ', exact: true }).click()
  await expect(page.getByTestId('order-detail-status')).toHaveText('В работе')
  await setDemoRole(page, 'client')
  await page.getByRole('button', { name: 'Открыть заказ DEMO-003' }).click()
  await expect(page.getByLabel('Согласованный срок', { exact: true })).toHaveValue('25.11.2026')
  await expect(page.getByTestId('order-detail-status')).toHaveText('В работе')
  await expect(page.getByTestId('order-item-summary').first()).toContainText('12000 шт.')
})

