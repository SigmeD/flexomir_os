import { expect, test } from '@playwright/test'
import { chooseMore, commitItem, fillItem, setDemoRole } from './helpers/orders'

test('optional integer fields reject text and malformed paste while keeping valid digits', async ({ page, context }, testInfo) => {
  const clipboardSupported = testInfo.project.name.includes('chromium')
  if (clipboardSupported) await context.grantPermissions(['clipboard-read', 'clipboard-write'])
  await page.goto('/?view=client-orders')
  await page.getByRole('button', { name: 'Добавить заказ', exact: true }).click()
  await page.getByRole('button', { name: 'Добавить позицию', exact: true }).click()
  const labels = page.getByLabel('Этикеток в рулоне')
  const inks = page.getByLabel('Количество красок')
  await labels.fill('12')
  await labels.press('End')
  await labels.press('A')
  await expect(labels).toHaveValue('12')
  await inks.fill('3')
  await inks.evaluate((input: HTMLInputElement) => input.focus())
  if (clipboardSupported) {
    await page.evaluate(() => navigator.clipboard.writeText('e2'))
    await inks.press('ControlOrMeta+V')
  } else await page.keyboard.insertText('e2')
  await expect(inks).toHaveValue('3')
  await labels.fill('')
  await expect(labels).toHaveValue('')
  await fillItem(page)
  await commitItem(page)
})

test('client send requires confirmation and dismissal preserves the same draft', async ({ page }) => {
  await page.goto('/?view=client-orders')
  await page.getByRole('button', { name: 'Добавить заказ', exact: true }).click()
  const id = await page.getByTestId('order-composer').getAttribute('data-order-id')
  await page.getByRole('button', { name: 'Добавить позицию', exact: true }).click()
  await fillItem(page)
  await commitItem(page)
  const send = page.getByRole('button', { name: 'Передать менеджеру (демо)' })
  await send.click()
  const dialog = page.getByRole('alertdialog', { name: 'Отправить заказ?' })
  await expect(dialog).toBeVisible()
  await dialog.getByRole('button', { name: 'Нет', exact: true }).click()
  await expect(page.getByTestId('order-composer')).toHaveAttribute('data-order-id', id!)
  await expect(page.getByTestId('order-item-summary')).toHaveCount(1)
  await send.click()
  await page.keyboard.press('Escape')
  await expect(page.getByTestId('order-composer')).toHaveAttribute('data-order-id', id!)
  await send.click()
  await dialog.getByRole('button', { name: 'Да', exact: true }).click()
  await expect(page.getByTestId('order-detail')).toHaveAttribute('data-order-id', id!)
  await expect(page.getByTestId('order-detail-status')).toHaveText('На рассмотрении')
  await chooseMore(page, 'Выйти')
  await expect(page.getByRole('button', { name: 'Открыть заказ ' + id })).toBeVisible()
})

test('cancelled order restores the same ID and content after confirmation', async ({ page }) => {
  await page.goto('/?view=client-orders')
  await page.getByRole('button', { name: 'Добавить заказ', exact: true }).click()
  const id = await page.getByTestId('order-composer').getAttribute('data-order-id')
  await page.getByRole('button', { name: 'Добавить позицию', exact: true }).click()
  await fillItem(page)
  await commitItem(page)
  await page.getByRole('button', { name: 'Передать менеджеру (демо)' }).click()
  await page.getByRole('alertdialog', { name: 'Отправить заказ?' }).getByRole('button', { name: 'Да' }).click()
  await chooseMore(page, 'Отменить заказ')
  await page.getByRole('alertdialog', { name: 'Отменить заказ?' }).getByRole('button', { name: 'Да' }).click()
  await chooseMore(page, 'Восстановить заказ')
  const restore = page.getByRole('alertdialog', { name: 'Восстановить заказ?' })
  await restore.getByRole('button', { name: 'Нет' }).click()
  await expect(page.getByTestId('order-detail-status')).toHaveText('Отменён')
  await chooseMore(page, 'Восстановить заказ')
  await restore.getByRole('button', { name: 'Да' }).click()
  await expect(page.getByTestId('order-detail')).toHaveAttribute('data-order-id', id!)
  await expect(page.getByTestId('order-detail-status')).toHaveText('На рассмотрении')
  await expect(page.getByTestId('order-item-summary')).toHaveCount(1)
})

test('confirmed removal hides only the cancelled client order in this demo session', async ({ page }) => {
  await page.goto('/?view=client-orders&demoTools=1')
  await page.getByRole('button', { name: 'Добавить заказ', exact: true }).click()
  const id = await page.getByTestId('order-composer').getAttribute('data-order-id')
  await page.getByRole('button', { name: 'Добавить позицию', exact: true }).click()
  await fillItem(page)
  await commitItem(page)
  await page.getByRole('button', { name: 'Передать менеджеру (демо)' }).click()
  await page.getByRole('alertdialog', { name: 'Отправить заказ?' }).getByRole('button', { name: 'Да' }).click()
  await chooseMore(page, 'Отменить заказ')
  await page.getByRole('alertdialog', { name: 'Отменить заказ?' }).getByRole('button', { name: 'Да' }).click()
  await chooseMore(page, 'Удалить заказ')
  const remove = page.getByRole('alertdialog', { name: 'Удалить заказ?' })
  await page.keyboard.press('Escape')
  await expect(page.getByTestId('order-detail-status')).toHaveText('Отменён')
  await chooseMore(page, 'Удалить заказ')
  await remove.getByRole('button', { name: 'Удалить' }).click()
  await expect(page.getByTestId('client-orders-list')).toBeVisible()
  await expect(page.getByRole('button', { name: 'Открыть заказ ' + id })).toHaveCount(0)
  await expect(page.getByRole('button', { name: 'Открыть заказ DEMO-003' })).toBeVisible()
  await setDemoRole(page, 'manager')
  await expect(page.getByRole('button', { name: 'Открыть заказ ' + id })).toBeVisible()
  await page.getByRole('button', { name: 'Открыть заказ ' + id }).click()
  await expect(page.getByTestId('order-detail-status')).toHaveText('Отменён')
  await page.getByRole('button', { name: 'Ещё' }).click()
  await expect(page.getByRole('menuitem', { name: 'Восстановить заказ' })).toHaveCount(0)
  await expect(page.getByRole('menuitem', { name: 'Удалить заказ' })).toHaveCount(0)
})
