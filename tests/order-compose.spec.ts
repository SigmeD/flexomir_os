import { expect, test, type Page } from '@playwright/test'

async function fillItem(page: Page, name = 'Этикетка DEMO') {
  await page.getByLabel('Наименование продукции', { exact: true }).fill(name)
  await page.getByLabel('Количество', { exact: true }).fill('500')
  await page.getByLabel('Флексопечать', { exact: true }).check()
  await page.getByLabel('Форма', { exact: true }).selectOption('Прямоугольная')
  await page.getByLabel('Ширина, мм', { exact: true }).fill('100')
  await page.getByLabel('Высота, мм', { exact: true }).fill('150')
  await page.getByLabel('Материал', { exact: true }).selectOption('Бумага')
  await page.getByLabel('Нужна помощь с макетом', { exact: true }).check()
}

test('A: new draft adds 0/1/N items explicitly, edits stable IDs and reverts dirty values', async ({ page }) => {
  await page.goto('/?view=client-orders')
  await page.getByRole('button', { name: 'Добавить заказ', exact: true }).click()
  const composer = page.getByTestId('order-composer')
  const id = await composer.getAttribute('data-order-id')
  await expect(page.getByRole('button', { name: 'Передать менеджеру (демо)', exact: true })).toBeDisabled()
  await page.getByRole('button', { name: 'Добавить позицию', exact: true }).click()
  await expect(page.getByRole('button', { name: 'Сохранить позицию', exact: true })).toBeDisabled()
  await fillItem(page)
  await page.getByRole('button', { name: 'Сохранить позицию', exact: true }).click()
  const first = composer.locator('[data-item-id]').first()
  const itemId = await first.getAttribute('data-item-id')
  await expect(composer.getByTestId('order-item-summary')).toHaveCount(1)
  await page.getByRole('button', { name: 'Изменить позицию 1', exact: true }).click()
  await expect(page.getByRole('button', { name: 'Сохранить позицию', exact: true })).toBeDisabled()
  await page.getByLabel('Количество', { exact: true }).fill('700')
  await expect(page.getByRole('status')).toContainText('Есть несохранённые изменения')
  await page.getByRole('button', { name: 'Восстановить значения', exact: true }).click()
  await expect(page.getByLabel('Количество', { exact: true })).toHaveValue('500')
  await page.getByLabel('Количество', { exact: true }).fill('800')
  await page.getByRole('button', { name: 'Сохранить позицию', exact: true }).click()
  expect(await first.getAttribute('data-item-id')).toBe(itemId)
  await expect(first).toContainText('800 шт.')
  await page.getByRole('button', { name: 'Добавить позицию', exact: true }).click()
  await page.getByRole('button', { name: 'Закрыть форму позиции', exact: true }).click()
  await expect(composer.getByTestId('order-item-summary')).toHaveCount(1)
  await page.getByRole('button', { name: 'Добавить позицию', exact: true }).click()
  await fillItem(page, 'Вторая DEMO')
  await page.getByRole('button', { name: 'Сохранить позицию', exact: true }).click()
  await expect(composer.getByTestId('order-item-summary')).toHaveCount(2)
  await page.getByLabel('Желаемый срок', { exact: true }).fill('2026-12-01')
  await page.getByLabel('Комментарий к заказу', { exact: true }).fill('Общий комментарий DEMO')
  await expect(page.getByRole('button', { name: 'К списку заказов', exact: true })).toBeDisabled()
  await page.getByRole('button', { name: 'Сохранить черновик', exact: true }).click()
  await page.getByRole('button', { name: 'К списку заказов', exact: true }).click()
  await page.getByRole('button', { name: 'Открыть заказ ' + id, exact: true }).click()
  await expect(composer.getByTestId('order-item-summary')).toHaveCount(2)
  await expect(page.getByLabel('Желаемый срок', { exact: true })).toHaveValue('2026-12-01')
  await expect(page.getByLabel('Комментарий к заказу', { exact: true })).toHaveValue('Общий комментарий DEMO')
})

test('A: artwork help is exclusive; local file remains selected, library and deletion stay unavailable', async ({ page }) => {
  await page.goto('/?view=client-orders')
  await page.getByRole('button', { name: 'Добавить заказ', exact: true }).click()
  await page.getByRole('button', { name: 'Добавить позицию', exact: true }).click()
  await fillItem(page)
  await expect(page.getByLabel('Выбрать файл макета', { exact: true })).toHaveCount(0)
  await page.getByLabel('Нужна помощь с макетом', { exact: true }).uncheck()
  await expect(page.getByRole('button', { name: 'Мои макеты', exact: true })).toBeDisabled()
  await page.getByLabel('Выбрать файл макета', { exact: true }).setInputFiles({ name: 'demo.txt', mimeType: 'text/plain', buffer: Buffer.from('synthetic') })
  await expect(page.getByText('Выбран локально: demo.txt', { exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'Сохранить позицию', exact: true }).click()
  await expect(page.getByTestId('order-item-summary')).toContainText('не загружен')
  await expect(page.getByRole('button', { name: /Удалить/ })).toBeDisabled()
})

test('B: completed More duplicates into the same composer, keeps source immutable and resets dates/files', async ({ page }) => {
  await page.goto('/?view=client-orders')
  await page.getByRole('button', { name: 'Открыть заказ DEMO-007', exact: true }).click()
  const source = await page.getByTestId('order-detail').innerText()
  const sourceIds = await page.getByTestId('order-item-summary').evaluateAll(nodes => nodes.map(node => node.getAttribute('data-item-id')))
  await page.getByRole('button', { name: 'Ещё', exact: true }).click()
  await expect(page.getByRole('menuitem', { name: 'Дублировать заказ', exact: true })).toBeFocused()
  await page.keyboard.press('Escape')
  await expect(page.getByRole('button', { name: 'Ещё', exact: true })).toBeFocused()
  await page.getByRole('button', { name: 'Ещё', exact: true }).click()
  await page.getByRole('menuitem', { name: 'Дублировать заказ', exact: true }).click()
  const composer = page.getByTestId('order-composer')
  const newId = await composer.getAttribute('data-order-id')
  expect(newId).not.toBe('DEMO-007')
  await expect(composer.getByTestId('order-item-summary')).toHaveCount(2)
  const clonedIds = await composer.locator('li[data-item-id]').evaluateAll(nodes => nodes.map(node => node.getAttribute('data-item-id')))
  expect(clonedIds.every(id => id && !sourceIds.includes(id))).toBe(true)
  await expect(page.getByLabel('Желаемый срок', { exact: true })).toHaveValue('')
  await expect(page.getByRole('button', { name: 'Передать менеджеру (демо)', exact: true })).toBeDisabled()
  await page.getByRole('button', { name: 'Изменить позицию 1', exact: true }).click()
  await expect(page.getByText(/Исходный макет недоступен:/)).toBeVisible()
  await page.getByLabel('Количество', { exact: true }).fill('1200')
  await page.getByLabel('Нужна помощь с макетом', { exact: true }).check()
  await page.getByRole('button', { name: 'Сохранить позицию', exact: true }).click()
  await expect(page.getByRole('button', { name: 'Передать менеджеру (демо)', exact: true })).toBeEnabled()
  await page.getByRole('button', { name: 'К списку заказов', exact: true }).click()
  await page.getByRole('button', { name: 'Открыть заказ DEMO-007', exact: true }).click()
  expect(await page.getByTestId('order-detail').innerText()).toBe(source)
  await page.getByRole('button', { name: 'Ещё', exact: true }).click()
  await page.getByRole('menuitem', { name: 'Дублировать заказ', exact: true }).click()
  expect(await composer.getAttribute('data-order-id')).not.toBe(newId)
  await expect(composer.getByTestId('order-item-summary').first()).toContainText('500 шт.')
})
