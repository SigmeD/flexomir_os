test('A: exclusive artwork HELP/local file; More deletion unavailable and demo library available', async ({ page }) => {
  await page.goto('/?view=client-orders')
  await page.getByRole('button', { name: 'Добавить заказ', exact: true }).click()
  await page.getByRole('button', { name: 'Добавить позицию', exact: true }).click()
  await fillItem(page)
  await expect(page.getByLabel('Выбрать файл макета')).toHaveCount(0)
  await page.getByLabel('Нужна помощь с макетом').uncheck()
  await expect(page.getByRole('button', { name: 'Мои макеты', exact: true })).toBeEnabled()
  await page.getByLabel('Выбрать файл макета').setInputFiles({ name: 'demo.txt', mimeType: 'text/plain', buffer: Buffer.from('synthetic') })
  await expect(page.getByText('Выбран локально: demo.txt', { exact: true })).toBeVisible()
  await page.evaluate(() => {
    const zone = document.querySelector('.fos-artwork-source__dropzone')!
    const over = new Event('dragover', { bubbles: true, cancelable: true })
    zone.dispatchEvent(over)
    const drop = new Event('drop', { bubbles: true, cancelable: true })
    Object.defineProperty(drop, 'dataTransfer', { value: { files: [new File(['synthetic'], 'replacement-demo.txt', { type: 'text/plain' })] } })
    zone.dispatchEvent(drop)
  })
  await expect(page.getByText('Выбран локально: replacement-demo.txt', { exact: true })).toBeVisible()
  await commitItem(page)
  await expect(page.getByTestId('order-item-summary')).toContainText('replacement-demo.txt (не загружен)')
  await page.getByRole('button', { name: 'Ещё', exact: true }).click()
  await expect(page.getByRole('menuitem', { name: /Удалить черновик/ })).toBeDisabled()
  await page.keyboard.press('Escape')
  await expect(page.getByRole('button', { name: 'Ещё', exact: true })).toBeFocused()
})

test('B: completed More→duplicate same composer, source immutable, fresh IDs and dates/files reset', async ({ page }) => {
  await page.goto('/?view=client-orders')
  await page.getByRole('button', { name: 'Открыть заказ DEMO-007' }).click()
  const source = await detailData(page)
  const sourceIds = await page.getByTestId('order-item-summary').evaluateAll(nodes => nodes.map(node => node.getAttribute('data-item-id')))
  await page.getByRole('button', { name: 'Ещё', exact: true }).focus()
  await page.keyboard.press('ArrowDown')
  await expect(page.getByRole('menuitem', { name: 'Дублировать заказ' })).toBeFocused()
  await page.keyboard.press('Escape')
  await expect(page.getByRole('button', { name: 'Ещё', exact: true })).toBeFocused()
  await chooseMore(page, 'Дублировать заказ')
  const composer = page.getByTestId('order-composer'), newId = await composer.getAttribute('data-order-id')
  expect(newId).not.toBe('DEMO-007')
  await expect(composer.getByTestId('order-item-summary')).toHaveCount(2)
  const clonedIds = await composer.locator('li[data-item-id]').evaluateAll(nodes => nodes.map(node => node.getAttribute('data-item-id')))
  expect(clonedIds.every(id => id && !sourceIds.includes(id))).toBe(true)
  await expect(page.getByLabel('Желаемый срок', { exact: true })).toHaveValue('')
  await expect(page.getByRole('button', { name: 'Передать менеджеру (демо)' })).toBeDisabled()
  await page.getByRole('button', { name: 'Изменить позицию 1' }).click()
  await expect(page.getByText(/Исходный макет недоступен:/)).toBeVisible()
  await page.getByRole('button', { name: 'Ещё', exact: true }).click()
  await expect(page.getByRole('menuitem', { name: /Дублировать позицию/ })).toBeDisabled()
  await expect(page.getByRole('menuitem', { name: /Удалить позицию/ })).toBeDisabled()
  await page.keyboard.press('Escape')
  await expect(page.getByTestId('order-item-form')).toBeVisible()
  await page.getByLabel('Количество', { exact: true }).fill('1200')
  await page.getByLabel('Нужна помощь с макетом').check()
  await commitItem(page)
  await expect(page.getByRole('button', { name: 'Передать менеджеру (демо)' })).toBeEnabled()
  await backToOrders(page)
  await page.getByRole('button', { name: 'Открыть заказ DEMO-007' }).click()
  expect(await detailData(page)).toEqual(source)
  await chooseMore(page, 'Дублировать заказ')
  expect(await composer.getAttribute('data-order-id')).not.toBe(newId)
  await expect(composer.getByTestId('order-item-summary').first()).toContainText('500 шт.')
})

