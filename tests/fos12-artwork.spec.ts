test('FOS12 fixture disabled source rejects native/drop/HELP/library changes and can be enabled', async ({ page }) => {
  await page.goto('/tests/fixtures/artwork-source.html?state=library&disabled=1')
  const artwork = source(page)
  await expect(artwork.getByRole('button', { name: 'Заменить макет', exact: true })).toBeDisabled()
  await expect(artwork.getByRole('button', { name: 'Выбрать файл', exact: true })).toBeDisabled()
  await expect(artwork.getByRole('checkbox')).toBeDisabled()
  await expect(artwork.locator('input[type=file]')).toBeDisabled()
  await page.getByLabel('Выбрать файл макета', { exact: true }).setInputFiles(localFile())
  const transfer = await page.evaluateHandle(() => {
    const data = new DataTransfer()
    data.items.add(new File(['synthetic'], 'ignored.txt'))
    return data
  })
  await artwork.locator('.fos-artwork-source__dropzone').dispatchEvent('drop', { dataTransfer: transfer })
  await artwork.getByRole('button', { name: 'Заменить макет', exact: true }).evaluate(node => (node as HTMLButtonElement).click())
  await expect(page.getByTestId('changes')).toHaveText('0')
  await expect(page.getByTestId('library-opens')).toHaveText('0')
  await expect(artwork).toHaveAttribute('data-artwork-state', 'library')
  await page.getByLabel('Заблокировать поле', { exact: true }).uncheck()
  await artwork.getByRole('button', { name: 'Заменить макет', exact: true }).click()
  await expect(page.getByTestId('library-opens')).toHaveText('1')
  await page.getByLabel('Выбрать файл макета', { exact: true }).setInputFiles(localFile())
  await expect(page.getByTestId('changes')).toHaveText('1')
  await expect(artwork).toHaveAttribute('data-artwork-state', 'local')
})

test('FOS12 fixture reports caller error and preserves a local alternative without a library callback', async ({ page }) => {
  await page.goto('/tests/fixtures/artwork-source.html?state=library&library=off&error=1')
  const artwork = source(page)
  await expect(artwork.getByRole('alert')).toHaveText('Тестовая ошибка поля')
  await expect(artwork.getByRole('button', { name: 'Заменить макет', exact: true })).toBeDisabled()
  const select = artwork.getByRole('button', { name: 'Выбрать файл', exact: true })
  await expect(select).toBeEnabled()
  await select.focus()
  const chooser = page.waitForEvent('filechooser')
  await page.keyboard.press('Enter')
  await (await chooser).setFiles(localFile())
  await expect(artwork).toHaveAttribute('data-artwork-state', 'local')
  await expect(page.getByTestId('changes')).toHaveText('1')
  await expect(artwork).toContainText('Файл не загружен на сервер')
  expect((await new AxeBuilder({ page }).analyze()).violations).toEqual([])
})

