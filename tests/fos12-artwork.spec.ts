import { expect, test, type Page } from '@playwright/test'
import AxeBuilder from '@axe-core/playwright'
import { chooseMore, commitItem, fillItem } from './helpers/orders'

const pilot = '/?view=client-orders&artworkStates=pilot'
const localFile = (name = 'synthetic-artwork.pdf') => ({ name, mimeType: 'application/pdf', buffer: Buffer.from('synthetic fixture, not uploaded') })
const source = (page: Page) => page.locator('.fos-artwork-source')

async function newItem(page: Page, url = pilot) {
  await page.goto(url)
  await page.getByRole('button', { name: 'Добавить заказ', exact: true }).click()
  await page.getByRole('button', { name: 'Добавить позицию', exact: true }).click()
  await page.evaluate(() => document.fonts.ready)
}

async function chooseLibrary(page: Page, id = 'demo-layout-01', trigger = 'Мои макеты') {
  await source(page).getByRole('button', { name: trigger, exact: true }).click()
  await expect(page.getByTestId('layout-picker')).toBeVisible()
  await page.getByTestId(`layout-row-${id}`).click()
  await page.getByRole('button', { name: 'Выбрать макет', exact: true }).click()
  await expect(page.getByTestId('order-item-form')).toBeVisible()
}

test('FOS12 library selection offers the right replacement and preserves empty chooser/cancel', async ({ page }, info) => {
  await newItem(page)
  await chooseLibrary(page)
  await page.screenshot({ path: info.outputPath('library-before-assertion.png'), fullPage: true })
  const artwork = source(page)
  await expect(artwork.getByRole('button', { name: 'Заменить макет', exact: true })).toBeVisible()
  await expect(artwork).toHaveAttribute('data-artwork-state', 'library')
  await expect(artwork).toContainText('Выбран из библиотеки: Этикетка 100×150')
  await expect(artwork.getByRole('button', { name: 'Загрузить', exact: true })).toHaveCount(0)
  await expect(artwork.getByText('Выберите файл или перетащите сюда', { exact: true })).toHaveCount(0)
  const chooserEvent = page.waitForEvent('filechooser')
  await artwork.getByRole('button', { name: 'Выбрать файл', exact: true }).click()
  await (await chooserEvent).setFiles([])
  await page.getByLabel('Выбрать файл макета', { exact: true }).dispatchEvent('cancel')
  await expect(artwork).toHaveAttribute('data-artwork-state', 'library')
  await expect(artwork).toContainText('Этикетка 100×150')
  await expect(artwork).toContainText('Только демосессия')
  await artwork.getByRole('button', { name: 'Заменить макет', exact: true }).click()
  await page.keyboard.press('Escape')
  await expect(artwork).toHaveAttribute('data-artwork-state', 'library')
  await expect(artwork.getByRole('button', { name: 'Заменить макет', exact: true })).toBeFocused()
  await chooseLibrary(page, 'demo-layout-02', 'Заменить макет')
  await expect(artwork).toContainText('Выбран из библиотеки: Визитка двусторонняя')
  await expect(artwork.getByRole('button', { name: 'Заменить макет', exact: true })).toBeFocused()
})

test('FOS12 local/library/help transitions keep one native chooser and never claim upload', async ({ page }) => {
  await newItem(page)
  const artwork = source(page)
  await expect(artwork).toHaveAttribute('data-artwork-state', 'empty')
  await page.getByLabel('Выбрать файл макета', { exact: true }).setInputFiles(localFile())
  await expect(artwork).toHaveAttribute('data-artwork-state', 'local')
  await expect(artwork).toContainText('Выбран локально: synthetic-artwork.pdf')
  await expect(artwork).toContainText('Файл не загружен на сервер')
  await chooseLibrary(page)
  await expect(artwork).toHaveAttribute('data-artwork-state', 'library')
  const chooserEvent = page.waitForEvent('filechooser')
  await artwork.getByRole('button', { name: 'Выбрать файл', exact: true }).click()
  await (await chooserEvent).setFiles(localFile('replacement.pdf'))
  await expect(artwork).toHaveAttribute('data-artwork-state', 'local')
  await expect(artwork).toContainText('replacement.pdf')
  await expect(artwork).not.toContainText('Этикетка 100×150')
  await expect(page.getByLabel('Выбрать файл макета', { exact: true })).toHaveCount(1)
  const help = page.getByLabel('Нужна помощь с макетом', { exact: true })
  await help.focus()
  await page.keyboard.press('Space')
  await expect(artwork).toHaveAttribute('data-artwork-state', 'help')
  await expect(artwork.locator('input[type=file]')).toBeHidden()
  await expect(artwork.locator('input[type=file]')).toBeDisabled()
  await expect(help).toBeFocused()
  await page.keyboard.press('Space')
  await expect(artwork).toHaveAttribute('data-artwork-state', 'empty')
  await expect(help).toBeFocused()
  await expect(artwork).not.toContainText('replacement.pdf')
  await expect(artwork.getByRole('button', { name: 'Загрузить', exact: true })).toBeVisible()
})

test('FOS12 a file drop replaces a source, while a drop on options does not', async ({ page }) => {
  await newItem(page)
  await chooseLibrary(page)
  const transfer = await page.evaluateHandle(() => {
    const data = new DataTransfer()
    data.items.add(new File(['synthetic'], 'dropped.txt', { type: 'text/plain' }))
    return data
  })
  await source(page).locator('.fos-artwork-source__options').dispatchEvent('drop', { dataTransfer: transfer })
  await expect(source(page)).toHaveAttribute('data-artwork-state', 'library')
  await source(page).locator('.fos-artwork-source__dropzone').dispatchEvent('drop', { dataTransfer: transfer })
  await expect(source(page)).toHaveAttribute('data-artwork-state', 'local')
  await expect(source(page)).toContainText('Выбран локально: dropped.txt')
})

test('FOS12 unavailable remains honest until actual replacement; IDs and save/cancel semantics survive', async ({ page }, info) => {
  await page.goto(pilot)
  await page.locator('[data-order-open="DEMO-007"]').click()
  await chooseMore(page, 'Дублировать заказ')
  const composer = page.getByTestId('order-composer')
  const orderId = await composer.getAttribute('data-order-id')
  const row = composer.locator('li[data-item-id]').first()
  const itemId = await row.getAttribute('data-item-id')
  await page.getByRole('button', { name: 'Изменить позицию 1' }).click()
  await expect(source(page)).toHaveAttribute('data-artwork-state', 'unavailable')
  await expect(source(page)).toContainText('Исходный макет недоступен:')
  await expect(page.getByRole('button', { name: 'Сохранить позицию', exact: true })).toBeDisabled()
  const chooser = page.waitForEvent('filechooser')
  await source(page).getByRole('button', { name: 'Выбрать файл', exact: true }).click()
  await (await chooser).setFiles([])
  await expect(source(page)).toHaveAttribute('data-artwork-state', 'unavailable')
  await page.screenshot({ path: info.outputPath('unavailable.png'), fullPage: true })
  await page.getByLabel('Выбрать файл макета', { exact: true }).setInputFiles(localFile())
  await expect(source(page)).toHaveAttribute('data-artwork-state', 'local')
  await expect(source(page)).not.toContainText('Исходный макет недоступен:')
  await expect(page.getByRole('button', { name: 'Сохранить позицию', exact: true })).toBeEnabled()
  await commitItem(page)
  await expect(composer).toHaveAttribute('data-order-id', orderId!)
  await expect(row).toHaveAttribute('data-item-id', itemId!)
  await page.getByRole('button', { name: 'Изменить позицию 1' }).click()
  await chooseLibrary(page)
  await chooseMore(page, 'Отменить изменения')
  await page.getByRole('button', { name: 'Изменить позицию 1' }).click()
  await expect(source(page)).toHaveAttribute('data-artwork-state', 'local')
  await expect(source(page)).toContainText('synthetic-artwork.pdf')
  await expect(page.getByRole('button', { name: 'Сохранить позицию', exact: true })).toBeDisabled()
})

