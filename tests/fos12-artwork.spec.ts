    await chooseLibrary(page)
    await expect(artwork).toHaveAttribute('data-artwork-state', 'library')
    expect((await box.boundingBox())!.width).toBe(original!.width)
    await page.screenshot({ path: info.outputPath(`library-${width}.png`), fullPage: true })
