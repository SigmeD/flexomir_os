import { test, expect } from '@playwright/test'
import AxeBuilder from '@axe-core/playwright'
import { fillItem, commitItem } from './helpers/orders'

for (const width of [1440, 1024, 768, 390, 320]) {
  test(`C LAY01/02/07 library preview and local upload ${width}`, async ({ page }, info) => {
    await page.setViewportSize({ width, height: 960 })
    await page.goto('/?view=client-layouts')
    await expect(page.getByRole('heading', { level: 1 })).toHaveText('Мои макеты')
    await expect(page.getByTestId('layout-preview-notice')).toBeVisible()
    expect((await new AxeBuilder({ page }).analyze()).violations).toEqual([])
    await page.screenshot({ path: info.outputPath(`fes03-layout-list-${width}.png`), fullPage: true })
    await page.getByTestId('layout-row-demo-layout-01').click()
    await expect(page.getByRole('heading', { level: 1 })).toHaveText('Этикетка 100×150')
    await expect(page.getByRole('button', { name: 'Скачать', exact: true })).toBeDisabled()
    await expect(page.getByRole('button', { name: 'Посмотреть', exact: true })).toBeDisabled()
    expect((await new AxeBuilder({ page }).analyze()).violations).toEqual([])
    await page.screenshot({ path: info.outputPath(`fes03-layout-detail-${width}.png`), fullPage: true })
    await page.goBack()
    await expect(page.getByTestId('layout-row-demo-layout-01')).toBeFocused()
    await page.getByRole('button', { name: 'Добавить макет', exact: true }).click()
    const save = page.getByRole('button', { name: 'Сохранить макет в демосессии', exact: true })
    await expect(save).toBeDisabled()
    await page.screenshot({ path: info.outputPath(`fes03-layout-upload-empty-${width}.png`), fullPage: true })
    await page.getByLabel('Название макета', { exact: true }).fill('Локальный демонстрационный макет')
    await expect(save).toBeDisabled()
    await page.getByLabel('Выбрать исходный файл', { exact: true }).setInputFiles({ name: 'synthetic-layout.svg', mimeType: 'image/svg+xml', buffer: Buffer.from('<svg xmlns="http://www.w3.org/2000/svg" width="50" height="50"/>') })
    await expect(page.getByText('Выбран локально: synthetic-layout.svg', { exact: true })).toBeVisible()
    await page.getByLabel('Описание (необязательно)', { exact: true }).fill('Только demo metadata')
    await expect(save).toBeEnabled()
    expect((await new AxeBuilder({ page }).analyze()).violations).toEqual([])
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
    await page.screenshot({ path: info.outputPath(`fes03-layout-upload-selected-${width}.png`), fullPage: true })
    await save.click()
    await expect(page.getByRole('heading', { level: 1 })).toHaveText('Локальный демонстрационный макет')
    await expect(page.getByTestId('layout-detail')).toContainText('Только demo metadata')
    await expect(page.getByTestId('layout-preview-notice')).toContainText('не загружены на сервер')
    await page.reload()
    await expect(page.getByTestId(/layout-row-/)).toHaveCount(3)
  })

  test(`C LAY03/04/05/06/08/09 artwork selection and replacement ${width}`, async ({ page }) => {
    await page.setViewportSize({ width, height: 960 })
    await page.goto('/?view=client-orders')
    await page.getByRole('button', { name: 'Добавить заказ', exact: true }).click()
    await page.getByRole('button', { name: 'Добавить позицию', exact: true }).click()
    await fillItem(page)
    await page.getByLabel('Нужна помощь с макетом').uncheck()
    await page.getByRole('button', { name: 'Мои макеты', exact: true }).click()
    await expect(page.getByTestId('layout-picker')).toHaveAttribute('data-mode', 'select')
    const pickerBreadcrumbs = page.getByRole('navigation', { name: 'Хлебные крошки' })
    if (width >= 1024) {
      await expect(pickerBreadcrumbs).toContainText('Новая позиция')
      await expect(pickerBreadcrumbs).toContainText('Мои макеты')
      await expect(page.getByTestId('sidebar-nav-artworks')).toHaveAttribute('aria-current', 'page')
      await expect(page.getByTestId('sidebar-nav-artworks')).toBeEnabled()
      await expect(page.getByTestId('sidebar-nav-orders')).toBeEnabled()
      await pickerBreadcrumbs.getByRole('button', { name: 'Новая позиция', exact: true }).click()
      await expect(page.getByTestId('layout-picker')).toHaveCount(0)
      await expect(page.getByLabel('Наименование продукции')).toHaveValue('Этикетка DEMO')
      await expect(page.getByTestId('sidebar-nav-orders')).toHaveAttribute('aria-current', 'page')
      await page.getByRole('button', { name: 'Мои макеты', exact: true }).click()
      await expect(page.getByTestId('layout-picker')).toHaveAttribute('data-mode', 'select')
    } else {
      await page.getByTestId('navigation-drawer-trigger').click()
      await expect(page.getByRole('dialog').getByTestId('sidebar-nav-artworks')).toHaveAttribute('aria-current', 'page')
      await expect(page.getByRole('dialog').getByTestId('sidebar-nav-artworks')).toBeEnabled()
      await expect(page.getByRole('dialog').getByTestId('sidebar-nav-orders')).toBeEnabled()
      await page.keyboard.press('Escape')
    }
    await page.getByRole('button', { name: 'Добавить макет', exact: true }).click()
    await page.getByLabel('Название макета', { exact: true }).fill('Локальный выбор')
    await page.getByLabel('Выбрать исходный файл', { exact: true }).setInputFiles({ name: 'selection.txt', mimeType: 'text/plain', buffer: Buffer.from('synthetic') })
    await page.getByRole('button', { name: 'Сохранить макет в демосессии', exact: true }).click()
    await page.getByRole('button', { name: 'Выбрать макет', exact: true }).click()
    await expect(page.getByTestId('artwork-library-selection')).toContainText('Локальный выбор')
    await expect(page.getByTestId('layout-picker')).toHaveCount(0)
    await expect(page.getByTestId('client-orders-screen').getByTestId('sidebar-nav-orders')).toHaveAttribute('aria-current', 'page')
    await page.getByRole('button', { name: 'Мои макеты', exact: true }).click()
    await page.getByTestId('layout-row-demo-layout-01').click()
    await page.getByRole('button', { name: 'Выбрать макет', exact: true }).click()
    await expect(page.getByTestId('layout-picker')).toHaveCount(0)
    await expect(page.getByLabel('Наименование продукции')).toHaveValue('Этикетка DEMO')
    await expect(page.getByTestId('artwork-library-selection')).toContainText('Этикетка 100×150')
    await commitItem(page)
    await page.getByRole('button', { name: 'Изменить позицию 1' }).click()
    await page.getByRole('button', { name: 'Мои макеты', exact: true }).click()
    await expect(page.getByTestId('layout-picker')).toHaveAttribute('data-mode', 'replace')
    if (width >= 1024) {
      await expect(page.getByRole('navigation', { name: 'Хлебные крошки' })).toContainText('Этикетка DEMO')
      await expect(page.getByRole('navigation', { name: 'Хлебные крошки' })).toContainText('Мои макеты')
      await expect(page.getByTestId('client-orders-screen').getByTestId('sidebar-nav-artworks')).toHaveAttribute('aria-current', 'page')
    } else {
      await page.getByTestId('navigation-drawer-trigger').click()
      await expect(page.getByRole('dialog').getByTestId('sidebar-nav-artworks')).toHaveAttribute('aria-current', 'page')
      await page.keyboard.press('Escape')
    }
    await page.getByRole('button', { name: 'Добавить макет', exact: true }).click()
    await page.getByLabel('Название макета', { exact: true }).fill('Локальная замена')
    await page.getByLabel('Выбрать исходный файл', { exact: true }).setInputFiles({ name: 'replacement.txt', mimeType: 'text/plain', buffer: Buffer.from('synthetic') })
    await page.getByRole('button', { name: 'Сохранить макет в демосессии', exact: true }).click()
    await page.getByRole('button', { name: 'Выбрать макет', exact: true }).click()
    await expect(page.getByTestId('artwork-library-selection')).toContainText('Локальная замена')
    await commitItem(page)
    await expect(page.getByTestId('order-item-summary')).toContainText('Локальная замена')
    await expect(page.getByTestId('order-item-summary')).not.toContainText('Этикетка 100×150')
  })
}

test('C empty/error and cancelled picker retain the original item', async ({ page }) => {
  await page.goto('/?view=client-layouts&fixture=empty')
  await expect(page.getByTestId('layouts-empty')).toBeVisible()
  await page.goto('/?view=client-layouts&fixture=layout-error')
  await page.getByRole('button', { name: 'Добавить макет' }).click()
  await expect(page.getByRole('alert')).toContainText('Демо: файл не отправлен')
  await expect(page.getByRole('button', { name: 'Сохранить макет в демосессии' })).toBeDisabled()
  await page.goto('/?view=client-orders')
  await page.getByRole('button', { name: 'Добавить заказ', exact: true }).click()
  await page.getByRole('button', { name: 'Добавить позицию', exact: true }).click()
  await fillItem(page)
  await page.getByLabel('Нужна помощь с макетом').uncheck()
  await page.getByRole('button', { name: 'Мои макеты', exact: true }).click()
  await page.keyboard.press('Escape')
  await expect(page.getByTestId('layout-picker')).toHaveCount(0)
  await expect(page.getByLabel('Наименование продукции')).toHaveValue('Этикетка DEMO')
  await expect(page.getByRole('button', { name: 'Мои макеты', exact: true })).toBeFocused()
  await expect(page.getByTestId('artwork-library-selection')).toHaveCount(0)
})
