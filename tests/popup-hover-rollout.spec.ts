test('ordinary Manager field uses shared hover at five widths, including production', async ({ page }, info) => {
  test.setTimeout(60000)
  for (const width of [1440, 1024, 768, 390, 320]) {
    await page.setViewportSize({ width, height: 900 })
    await page.goto('/?view=manager-orders')
    await page.evaluate(() => document.fonts.ready)
    await page.getByRole('button', { name: 'Добавить заказ', exact: true }).click()
    const trigger = page.getByRole('combobox', { name: 'Компания', exact: true })
    await trigger.click()
    const popup = page.getByRole('listbox')
    await expect(popup).toHaveAttribute('data-hover-preview', 'v0.3')
    const row = popup.getByRole('option', { name: /^Компания 02/ })
    if (info.project.use.hasTouch !== true) {
      await row.hover()
      await aligned(popup, row)
      await expect(trigger).not.toContainText('Компания 02')
      await page.screenshot({ path: `output/playwright/popup-hover/evidence/${info.project.name}-company-${width}.png` })
    } else {
      await expect(popup.locator('[data-motion="travel"]')).toHaveCount(0)
    }
    if (info.project.use.hasTouch === true) await row.tap()
    else await row.click()
    await expect(popup).toBeHidden()
    await expect(trigger).toContainText('Компания 02')
    await expect(trigger).toBeFocused()
  }
})

