test('Owner 1 deleting the selected file preserves its same-name sibling and restores empty upload', async ({ page }) => {
  await newOrder(page)
  const picker = page.getByLabel('Выбрать подписной бланк', { exact: true })
  await picker.setInputFiles({ name: 'same.txt', mimeType: 'text/plain', buffer: Buffer.from('first') })
  await picker.setInputFiles({ name: 'same.txt', mimeType: 'text/plain', buffer: Buffer.from('second') })
  const cards = page.getByRole('button', { name: /Открыть документ Файл same\.txt / })
  await cards.last().click()
  await page.getByRole('dialog').getByRole('button', { name: 'Удалить документ', exact: true }).click()
  await expect(page.getByRole('dialog')).toHaveCount(0)
  await expect(cards).toHaveCount(1)
  await cards.first().click()
  const downloading = page.waitForEvent('download')
  await page.getByRole('link', { name: 'Скачать', exact: true }).click()
  const { readFile } = await import('node:fs/promises')
  expect(await readFile((await (await downloading).path())!, 'utf8')).toBe('first')
  await page.getByRole('button', { name: 'Удалить документ', exact: true }).click()
  await expect(cards).toHaveCount(0)
  await expect(page.locator('.fos-file-dropzone')).toBeVisible()
  await expect(page.getByRole('button', { name: 'Добавить подписной бланк', exact: true })).toBeFocused()
})

