test('Owner 4 release during permission request cancels late device access', async ({ page }) => {
  await page.addInitScript(() => {
    Object.assign(window, { ownerPending: { finish: undefined as undefined | ((stream: MediaStream) => void) } })
    navigator.mediaDevices.getUserMedia = () => new Promise(resolve => { (window as unknown as {ownerPending:{finish: typeof resolve}}).ownerPending.finish = resolve })
  })
  await newOrder(page)
  test.skip(!await page.evaluate(() => typeof MediaRecorder !== 'undefined'), 'Native recorder absent; fallback tested separately.')
  const button = page.locator('.fos-record-button')
  await button.scrollIntoViewIfNeeded()
  const box = (await button.boundingBox())!
  await page.mouse.move(box.x+22,box.y+22); await page.mouse.down()
  await expect(page.getByTestId('message-composer')).toHaveAttribute('data-state','AudioRecording')
  await page.mouse.up()
  await expect(page.getByTestId('message-composer')).toHaveAttribute('data-state','Empty')
  expect(await page.evaluate(async () => {
    const stream = document.createElement('canvas').captureStream(10)
    ;(window as unknown as {ownerPending:{finish:(stream:MediaStream)=>void}}).ownerPending.finish(stream)
    await new Promise(resolve=>setTimeout(resolve,50))
    return stream.getTracks().every(track=>track.readyState==='ended')
  })).toBe(true)
})

