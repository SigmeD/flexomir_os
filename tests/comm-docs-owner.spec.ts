async function syntheticDevices(page: Page) {
  await page.addInitScript(() => {
    const probe = { requests: 0, tracks: [] as MediaStreamTrack[] }
    Object.assign(window, { ownerCapture: probe })
    navigator.mediaDevices.getUserMedia = async constraints => {
      probe.requests++
      if (constraints?.video) {
        const canvas = document.createElement('canvas'); canvas.width = 160; canvas.height = 90
        const stream = canvas.captureStream(12)
        const timer = setInterval(() => { const ctx = canvas.getContext('2d')!; ctx.fillStyle = 'green'; ctx.fillRect(0,0,160,90) }, 50)
        stream.getTracks().forEach(track => { const stop = track.stop.bind(track); track.stop = () => { clearInterval(timer); stop() } })
        probe.tracks.push(...stream.getTracks()); return stream
      }
      const context = new AudioContext(), destination = context.createMediaStreamDestination(), oscillator = context.createOscillator()
      oscillator.connect(destination); oscillator.start()
      destination.stream.getTracks().forEach(track => { const stop = track.stop.bind(track); track.stop = () => { stop(); oscillator.stop(); void context.close() } })
      probe.tracks.push(...destination.stream.getTracks()); return destination.stream
    }
  })
}

test('Owner 4 short click switches smoothly; pointer hold records and release prepares without sending', async ({ page }, info) => {
  await syntheticDevices(page); await newOrder(page)
  test.skip(!await page.evaluate(() => typeof MediaRecorder !== 'undefined'), 'Native recorder absent; permission/unsupported fallback tested separately.')
  const button = page.locator('.fos-record-button')
  await expect(button).toHaveAttribute('data-mode', 'audio')
  await button.click()
  await expect(button).toHaveAttribute('data-mode', 'video')
  expect(await page.evaluate(() => (window as unknown as {ownerCapture:{requests:number}}).ownerCapture.requests)).toBe(0)
  const box = (await button.boundingBox())!
  await page.mouse.move(box.x + box.width/2, box.y + box.height/2); await page.mouse.down()
  await expect(page.getByTestId('message-composer')).toHaveAttribute('data-state', 'VideoRecording')
  await page.waitForTimeout(350)
  await page.mouse.move(box.x - 80, box.y); await page.mouse.up()
  await expect(page.getByTestId('message-composer')).toHaveAttribute('data-state', 'VideoReady')
  await expect(page.getByTestId('message-thread')).toHaveCount(0)
  await expect.poll(() => page.getByLabel('Просмотр записи').evaluate(video => (video as HTMLVideoElement).readyState)).toBeGreaterThanOrEqual(2)
  expect(await page.evaluate(() => (window as unknown as {ownerCapture:{tracks:MediaStreamTrack[]}}).ownerCapture.tracks.every(track => track.readyState === 'ended'))).toBe(true)
  await page.screenshot({path:`output/comm-docs/owner/${info.project.name}/video-ready.png`,fullPage:true})
  await page.getByRole('button',{name:'Отправить сообщение локально',exact:true}).click()
  await expect(page.getByTestId('message-thread').locator('video')).toHaveCount(1)
})

