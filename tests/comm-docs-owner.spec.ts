test('Owner 2 and 4 Save retains unsent audio/video draft without posting it and clears it after send', async ({ page }) => {
  await syntheticDevices(page)
  await page.goto('/?view=client-support&commDemo=1')
  test.skip(!await page.evaluate(() => typeof MediaRecorder !== 'undefined'), 'Native recorder absent; ordinary File/text draft and unsupported paths tested separately.')
  const row = page.getByTestId('ticket-row-client-01')
  await row.click()
  for (const kind of ['audio','video']) {
    const count = await page.getByTestId('message-thread').locator('article').count()
    const record = page.locator('.fos-record-button')
    if (kind === 'video') await record.click()
    await record.focus(); await page.keyboard.down('Space')
    await expect(page.getByTestId('message-composer')).toHaveAttribute('data-state',kind === 'audio' ? 'AudioRecording' : 'VideoRecording')
    await page.waitForTimeout(400); await page.keyboard.up('Space')
    await expect(page.getByTestId('message-composer')).toHaveAttribute('data-state',kind === 'audio' ? 'AudioReady' : 'VideoReady')
    await page.getByRole('button',{name:'Сохранить обращение',exact:true}).click()
    await row.click()
    await expect(page.getByTestId('message-composer')).toHaveAttribute('data-state',kind === 'audio' ? 'AudioReady' : 'VideoReady')
    await expect(page.getByTestId('message-thread').locator('article')).toHaveCount(count)
    if (kind === 'audio') await page.getByRole('button',{name:'Прослушать запись',exact:true}).click()
    await expect.poll(()=>page.locator('.fos-message-media '+kind).evaluate(el=>(el as HTMLMediaElement).readyState)).toBeGreaterThanOrEqual(2)
    await page.getByLabel('Сообщение',{exact:true}).fill('Сохранённый черновик '+kind)
    await page.getByRole('button',{name:'Отправить сообщение локально',exact:true}).click()
    await expect(page.getByTestId('message-thread').locator('article')).toHaveCount(count+1)
    await page.getByRole('button',{name:'Сохранить обращение',exact:true}).click(); await row.click()
    await expect(page.getByTestId('message-composer')).toHaveAttribute('data-state','Empty')
    await expect(page.locator('.fos-message-media')).toHaveCount(0)
  }
  const record = page.locator('.fos-record-button')
  await record.focus(); await page.keyboard.down('Space')
  await expect(page.getByTestId('message-composer')).toHaveAttribute('data-state','AudioRecording')
  await page.waitForTimeout(350); await page.keyboard.up('Space')
  await expect(page.getByTestId('message-composer')).toHaveAttribute('data-state','AudioReady')
  await page.getByRole('button',{name:'Удалить запись',exact:true}).click()
  await expect(page.getByRole('button',{name:'Сохранить обращение',exact:true})).toBeDisabled()
  await page.goBack(); await row.click()
  await expect(page.getByTestId('message-composer')).toHaveAttribute('data-state','Empty')
})
