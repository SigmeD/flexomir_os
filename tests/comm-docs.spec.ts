test('Q27/Q30/Q34/Q35 actual PDF pages, original download and modal focus', async ({ page }) => {
  page.on('pageerror', error => console.log('PDF pageerror', error.message))
  page.on('console', message => { if (message.type() === 'error' || message.type() === 'warning') console.log('PDF console', message.text()) })
  await page.goto('/?view=client-orders')
  await page.getByRole('button', { name: 'Добавить заказ', exact: true }).click()
  const original = syntheticPdf(2)
  await page.getByLabel('Выбрать подписной бланк').setInputFiles({ name: 'Синтетический.pdf', mimeType: 'application/pdf', buffer: original })
  const card = page.getByRole('button', { name: /Открыть документ PDF Синтетический\.pdf / })
  await card.click()
  const dialog = page.getByRole('dialog')
  await expect(dialog.locator('canvas')).toHaveCount(2, { timeout: 15000 })
  await expect(dialog.getByText('2 страницы', { exact: true })).toBeVisible()
  const downloadPromise = page.waitForEvent('download')
  await dialog.getByRole('link', { name: 'Скачать' }).click()
  const download = await downloadPromise
  expect(download.suggestedFilename()).toBe('Синтетический.pdf')
  const path = await download.path()
  const { readFile } = await import('node:fs/promises')
  expect(await readFile(path!)).toEqual(original)
  await page.keyboard.press('Escape')
  await expect(dialog).toHaveCount(0)
  await expect(card).toBeFocused()
  await page.getByLabel('Выбрать подписной бланк').setInputFiles({name:'Одна страница.pdf',mimeType:'application/pdf',buffer:syntheticPdf(1)})
  await page.getByRole('button',{name:/Открыть документ PDF Одна страница\.pdf /}).click()
  await expect(dialog.locator('canvas')).toHaveCount(1)
  await expect(dialog.getByText('1 страница',{exact:true})).toBeVisible()
  await page.keyboard.press('Escape')
})

