test('Q27–33 signed file drop/cancel preserve originals and same-name file identities; lock prevents default drop',async({page})=>{
  await page.goto('/?view=client-orders')
  await page.getByRole('button',{name:'Добавить заказ',exact:true}).click()
  await page.getByLabel('Выбрать подписной бланк').setInputFiles({name:'empty.txt',mimeType:'text/plain',buffer:Buffer.alloc(0)})
  await expect(page.getByRole('alert')).toContainText('Пустой файл нельзя добавить')
  const choosing=page.waitForEvent('filechooser')
  await page.getByText('Выберите файл или перетащите сюда',{exact:true}).click()
  await (await choosing).setFiles([])
  await expect(page.getByRole('button',{name:/Открыть документ/})).toHaveCount(0)
  await page.locator('.fos-file-dropzone').evaluate(root=>{
    const transfer=new DataTransfer();transfer.items.add(new File(['first'],'same.txt',{type:'text/plain'}))
    root.dispatchEvent(new DragEvent('drop',{dataTransfer:transfer,bubbles:true,cancelable:true}))
  })
  await page.getByLabel('Выбрать подписной бланк').setInputFiles({name:'same.txt',mimeType:'text/plain',buffer:Buffer.from('second')})
  const cards=page.getByRole('button',{name:/Открыть документ Файл same\.txt /})
  await expect(cards).toHaveCount(2)
  await cards.last().click()
  const downloading=page.waitForEvent('download')
  await page.getByRole('dialog').getByRole('link',{name:'Скачать',exact:true}).click()
  const original=await downloading, {readFile}=await import('node:fs/promises')
  expect(await readFile((await original.path())!,'utf8')).toBe('second')
  await page.keyboard.press('Escape')
  await expect(cards).toHaveCount(2)
  await page.goto('/?view=client-orders&fixture=item-actions-transfer')
  await page.getByRole('button',{name:'Открыть заказ DEMO-REVIEW-001'}).click()
  const prevented=await page.locator('.fos-signed-documents').evaluate(root=>{
    const transfer=new DataTransfer();transfer.items.add(new File(['blocked'],'blocked.txt',{type:'text/plain'}))
    const event=new DragEvent('drop',{dataTransfer:transfer,bubbles:true,cancelable:true});root.dispatchEvent(event);return event.defaultPrevented
  })
  expect(prevented).toBe(true)
  await expect(page.getByRole('button',{name:/Открыть документ Файл blocked\.txt /})).toHaveCount(0)
})

