test('CRUD message context reuses Glass and edits/deletes/copies without posting another message', async ({page,context,browserName}) => {
  if(browserName==='chromium')await context.grantPermissions(['clipboard-read','clipboard-write'])
  else await page.addInitScript(()=>Object.defineProperty(navigator,'clipboard',{value:{writeText:async(text:string)=>{Object.assign(window,{copiedMessage:text})}},configurable:true}))
  await page.goto('/?view=client-orders')
  await page.getByRole('button',{name:'Добавить заказ',exact:true}).click()
  await page.getByLabel('Сообщение',{exact:true}).fill('Original own message')
  await page.getByRole('button',{name:'Отправить сообщение локально',exact:true}).click()
  const message = page.locator('.fos-message').filter({hasText:'Original own message'})
  await message.click({button:'right'})
  const menu = page.getByRole('menu',{name:'Действия сообщения'})
  await expect(menu.locator('[data-motion-reference="FE11-v0.2"]')).toHaveCount(1)
  await page.getByRole('menuitem',{name:'Редактировать',exact:true}).click()
  const editor = page.getByTestId('message-editor')
  await editor.getByRole('textbox').fill('Edited own message')
  await editor.getByRole('button',{name:'Сохранить сообщение',exact:true}).click()
  await expect(page.locator('.fos-message')).toHaveCount(1)
  await expect(page.getByTestId('message-thread')).toContainText('Edited own message')
  const edited = page.locator('.fos-message').first()
  await edited.focus(); await page.keyboard.press('Shift+F10')
  await page.getByRole('menuitem',{name:'Копировать',exact:true}).click()
  expect(await page.evaluate(native=>native?navigator.clipboard.readText():(window as unknown as {copiedMessage:string}).copiedMessage,browserName==='chromium')).toBe('Edited own message')
  await edited.click({button:'right'})
  await page.getByRole('menuitem',{name:'Удалить',exact:true}).click()
  await expect(page.locator('.fos-message')).toHaveCount(0)
  await expect(page.getByLabel('Сообщение',{exact:true})).toBeVisible()
})

