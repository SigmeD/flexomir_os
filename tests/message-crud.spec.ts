test('CRUD touch hold uses shared menu, swipe cancels and Escape returns focus',async({page},info)=>{
  await page.goto('/?view=client-orders')
  await page.getByRole('button',{name:'Добавить заказ',exact:true}).click()
  await page.getByLabel('Сообщение',{exact:true}).fill('Long press')
  await page.getByRole('button',{name:'Отправить сообщение локально',exact:true}).click()
  const message=page.locator('.fos-message').first()
  await message.dispatchEvent('pointerdown',{pointerType:'touch',pointerId:8,isPrimary:true,clientX:100,clientY:200})
  await message.dispatchEvent('pointermove',{pointerType:'touch',pointerId:8,isPrimary:true,clientX:140,clientY:200})
  await page.waitForTimeout(550)
  await expect(page.getByRole('menu',{name:'Действия сообщения'})).toHaveCount(0)
  for(const width of [1440,768,390,320]){
    await page.setViewportSize({width,height:900});await message.scrollIntoViewIfNeeded()
    const box=(await message.boundingBox())!
    await message.dispatchEvent('pointerdown',{pointerType:'touch',pointerId:9,isPrimary:true,clientX:Math.min(width-4,box.x+box.width),clientY:box.y+20})
    const menu=page.getByRole('menu',{name:'Действия сообщения'})
    await expect(menu).toBeVisible()
    await message.dispatchEvent('pointerup',{pointerType:'touch',pointerId:9,isPrimary:true})
    const bounds=(await menu.boundingBox())!
    expect(bounds.x).toBeGreaterThanOrEqual(0);expect(bounds.x+bounds.width).toBeLessThanOrEqual(width)
    expect((await new AxeBuilder({page}).include('.fos-comments').include('[role=menu]').analyze()).violations).toEqual([])
    await page.screenshot({path:`output/comm-docs/crud/${info.project.name}/context-${width}.png`,fullPage:true})
    await page.keyboard.press('Escape');await expect(menu).toHaveCount(0);await expect(message).toBeFocused()
  }
})

