test('CRUD ticket Save commits pending inline edit; a late read blocks both Save paths',async({page})=>{
  await page.goto('/?view=client-support')
  await page.getByRole('button',{name:'Добавить обращение',exact:true}).click()
  await page.getByLabel('Тема',{exact:true}).fill('Race ticket')
  await page.getByLabel('Описание',{exact:true}).fill('Before edit')
  await page.getByRole('button',{name:'Сохранить обращение',exact:true}).click()
  const row=page.getByTestId('ticket-row-client-100');await row.click()
  await page.locator('.fos-message').first().click({button:'right'})
  await page.getByRole('menuitem',{name:'Редактировать',exact:true}).click()
  await page.getByTestId('message-editor').getByRole('textbox').fill('Committed by ticket Save')
  const save=page.getByRole('button',{name:'Сохранить обращение',exact:true})
  await expect(save).toBeEnabled();await save.click();await row.click()
  await expect(page.getByTestId('message-thread')).toContainText('Committed by ticket Save')
  await expect(save).toBeDisabled()
  await page.locator('.fos-message').first().click({button:'right'})
  await page.getByRole('menuitem',{name:'Редактировать',exact:true}).click()
  await page.getByTestId('message-editor').getByRole('textbox').fill('Must not commit')
  await page.evaluate(async()=>{
    // Local receipt fixture injects the same event the future API adapter supplies.
    const loaded=performance.getEntriesByType('resource').find(entry=>entry.name.includes('/src/components/messaging/local-communication.ts'))
    if(!loaded)throw new Error('Local adapter module was not loaded')
    const {localConversation}=await import(loaded.name)
    const chat=localConversation(JSON.stringify(['support','client','client-100']))
    if(!chat.read().length)throw new Error('Receipt fixture must target the mounted conversation')
    chat.markRead(chat.read().map((message:{id:string})=>message.id),'support')
  })
  await expect(save).toBeDisabled()
  await expect(page.getByRole('button',{name:'Сохранить сообщение',exact:true})).toBeDisabled()
  await expect(page.getByRole('alert')).toContainText('прочитано')
  await page.getByRole('button',{name:'Отменить',exact:true}).click()
  await expect(page.getByTestId('message-thread')).toContainText('Committed by ticket Save')
  await expect(page.getByTestId('message-thread')).not.toContainText('Must not commit')
})

