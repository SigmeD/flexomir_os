const fs = require('node:fs')
const path = require('node:path')
const { PNG } = require('pngjs')
const [reference, actual, target] = process.argv.slice(2)
if (!reference || !actual || !target) throw new Error('Provide reference.png actual.png output.png')
const left = PNG.sync.read(fs.readFileSync(reference)), right = PNG.sync.read(fs.readFileSync(actual))
const result = new PNG({ width: left.width + 24 + right.width, height: Math.max(left.height, right.height) })
result.data.fill(255)
PNG.bitblt(left, result, 0, 0, left.width, left.height, 0, 0)
PNG.bitblt(right, result, 0, 0, right.width, right.height, left.width + 24, 0)
fs.mkdirSync(path.dirname(target), { recursive: true })
fs.writeFileSync(target, PNG.sync.write(result))
process.stdout.write('Figma left / React right: ' + target + '\n')
